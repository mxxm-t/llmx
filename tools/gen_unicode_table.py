"""Writes src/core/unicode_class.hpp, the code-point classes a pretokenizer regex reads, from the Unicode 16.0.0 character database.

    python tools/gen_unicode_table.py --ucd DIR

DIR holds DerivedGeneralCategory.txt and PropList.txt of Unicode 16.0.0, each refused unless it has the SHA-256 pinned here (docs/ASSETS.md, The Unicode class table).
The classes are the general-category groups L, M, N, P and S and the White_Space property, which is what the regex engine's \\s holds.
Standard library only; the suite does not run it, and tests/tokenizer.py holds the header it wrote to the running Python's unicodedata.
"""

import argparse
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "src", "core", "unicode_class.hpp")
VERSION = "16.0.0"
PINNED = {
    "DerivedGeneralCategory.txt": "7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293",
    "PropList.txt": "53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583",
}
# The bit of each class, in the order the header's enum names them.
BITS = {"L": 1, "M": 2, "N": 4, "P": 8, "S": 16, "W": 32}


def read_pinned(directory, name):
    path = os.path.join(directory, name)
    with open(path, "rb") as f:
        raw = f.read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINNED[name]:
        raise SystemExit("%s has SHA-256 %s, not the pinned %s of Unicode %s" % (path, digest, PINNED[name], VERSION))
    return raw.decode("utf-8")


def entries(text):
    """Each data line's code-point range and first field."""
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = [field.strip() for field in line.split(";")[:2]]
        first, _, last = cps.partition("..")
        yield int(first, 16), int(last or first, 16), value


def class_bits(directory):
    """The class bits of every code point that has one."""
    bits = {}
    for first, last, category in entries(read_pinned(directory, "DerivedGeneralCategory.txt")):
        bit = BITS.get(category[0])
        if bit:
            for cp in range(first, last + 1):
                bits[cp] = bits.get(cp, 0) | bit
    for first, last, prop in entries(read_pinned(directory, "PropList.txt")):
        if prop == "White_Space":
            for cp in range(first, last + 1):
                bits[cp] = bits.get(cp, 0) | BITS["W"]
    return bits


def ranges(bits):
    """Runs of neighbouring code points with the same bits, in order."""
    out = []
    for cp in sorted(bits):
        if out and out[-1][1] == cp - 1 and out[-1][2] == bits[cp]:
            out[-1][1] = cp
        else:
            out.append([cp, cp, bits[cp]])
    return out


def header(runs):
    rows = ["{0x%x, 0x%x, %d}," % tuple(r) for r in runs]
    lines = []
    for i in range(0, len(rows), 6):
        lines.append("    " + " ".join(rows[i:i + 6]))
    return "\n".join([
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// The Unicode %s classes a pretokenizer regex reads: general categories L, M, N, P and S, and White_Space for \\s." % VERSION,
        "// Generated by tools/gen_unicode_table.py from DerivedGeneralCategory.txt and PropList.txt; do not hand-edit.",
        "",
        "namespace unicode_class {",
        "",
        "enum : uint8_t { L = 1, M = 2, N = 4, P = 8, S = 16, W = 32 };",
        "",
        "struct Range { uint32_t first, last; uint8_t bits; };",
        "",
        "// Sorted, disjoint runs of code points with the same bits; a code point in none has no class.",
        "inline constexpr Range kRanges[] = {",
    ] + lines + [
        "};",
        "",
        "// The class bits of `cp`, by binary search over the runs.",
        "inline uint8_t of(uint32_t cp) {",
        "    size_t lo = 0, hi = sizeof(kRanges) / sizeof(kRanges[0]);",
        "    while (lo < hi) {",
        "        size_t mid = (lo + hi) / 2;",
        "        if (kRanges[mid].last < cp) lo = mid + 1;",
        "        else if (kRanges[mid].first > cp) hi = mid;",
        "        else return kRanges[mid].bits;",
        "    }",
        "    return 0;",
        "}",
        "",
        "} // namespace unicode_class",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd", required=True, help="directory holding the pinned DerivedGeneralCategory.txt and PropList.txt")
    args = parser.parse_args()
    runs = ranges(class_bits(args.ucd))
    with open(OUTPUT, "w", encoding="ascii", newline="\n") as f:
        f.write(header(runs))
    print("wrote %s (%d runs)" % (OUTPUT, len(runs)))


if __name__ == "__main__":
    sys.exit(main())
