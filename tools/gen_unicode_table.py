"""Writes src/core/unicode_class.hpp, the code-point classes a pretokenizer regex reads, and src/core/unicode_nfc_table.inc, the tables NFC reads, from the Unicode 16.0.0 character database.

    python tools/gen_unicode_table.py --ucd DIR

DIR holds DerivedGeneralCategory.txt, PropList.txt, UnicodeData.txt and DerivedNormalizationProps.txt of Unicode 16.0.0, each refused unless it has the SHA-256 pinned here (docs/ASSETS.md, The Unicode class table).
The classes are the general-category groups L, M, N, P and S, the case of letters (Lu and Lt, or Ll) and the White_Space property, which is what the regex engine's \\s holds.
The NFC tables are the nonzero canonical combining classes, the canonical decompositions, the primary composites and the code points whose NFC quick check is not Yes.
Standard library only; the suite does not run it, and tests/tokenizer.py holds both files to the running Python's unicodedata.
"""

import argparse
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "src", "core", "unicode_class.hpp")
NFC_OUTPUT = os.path.join(ROOT, "src", "core", "unicode_nfc_table.inc")
VERSION = "16.0.0"
PINNED = {
    "DerivedGeneralCategory.txt": "7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293",
    "PropList.txt": "53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583",
    "UnicodeData.txt": "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f",
    "DerivedNormalizationProps.txt": "4d4c03892dea9146d674b686e495df2d55a28d071ac474041d73518f887abddc",
}
# The bit of each class, in the order the header's enum names them.
BITS = {"L": 1, "M": 2, "N": 4, "P": 8, "S": 16, "W": 32}
# The case bits a regex naming letter subcategories reads: LU for Lu and Lt, LL for Ll; Lm and Lo letters carry neither.
CASE_BITS = {"Lu": 64, "Lt": 64, "Ll": 128}


def read_pinned(directory, name):
    path = os.path.join(directory, name)
    with open(path, "rb") as f:
        raw = f.read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINNED[name]:
        raise SystemExit("%s has SHA-256 %s, not the pinned %s of Unicode %s" % (path, digest, PINNED[name], VERSION))
    return raw.decode("utf-8")


def entries(text):
    """Each data line's code-point range and first field."""
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = [field.strip() for field in line.split(";")[:2]]
        first, _, last = cps.partition("..")
        yield int(first, 16), int(last or first, 16), value


def class_bits(directory):
    """The class bits of every code point that has one."""
    bits = {}
    for first, last, category in entries(read_pinned(directory, "DerivedGeneralCategory.txt")):
        bit = BITS.get(category[0], 0) | CASE_BITS.get(category, 0)
        if bit:
            for cp in range(first, last + 1):
                bits[cp] = bits.get(cp, 0) | bit
    for first, last, prop in entries(read_pinned(directory, "PropList.txt")):
        if prop == "White_Space":
            for cp in range(first, last + 1):
                bits[cp] = bits.get(cp, 0) | BITS["W"]
    return bits


def ranges(bits):
    """Runs of neighbouring code points with the same bits, in order."""
    out = []
    for cp in sorted(bits):
        if out and out[-1][1] == cp - 1 and out[-1][2] == bits[cp]:
            out[-1][1] = cp
        else:
            out.append([cp, cp, bits[cp]])
    return out


def header(runs):
    rows = ["{0x%x, 0x%x, %d}," % tuple(r) for r in runs]
    lines = []
    for i in range(0, len(rows), 6):
        lines.append("    " + " ".join(rows[i:i + 6]))
    return "\n".join([
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// The Unicode %s classes a pretokenizer regex reads: general categories L, M, N, P and S, the case of letters, and White_Space for \\s." % VERSION,
        "// Generated by tools/gen_unicode_table.py from DerivedGeneralCategory.txt and PropList.txt; do not hand-edit.",
        "",
        "namespace unicode_class {",
        "",
        "// LU marks letters of categories Lu and Lt, LL letters of Ll; the eight bits are all taken.",
        "enum : uint8_t { L = 1, M = 2, N = 4, P = 8, S = 16, W = 32, LU = 64, LL = 128 };",
        "",
        "struct Range { uint32_t first, last; uint8_t bits; };",
        "",
        "// Sorted, disjoint runs of code points with the same bits; a code point in none has no class.",
        "inline constexpr Range kRanges[] = {",
    ] + lines + [
        "};",
        "",
        "// The class bits of `cp`, by binary search over the runs.",
        "inline uint8_t of(uint32_t cp) {",
        "    size_t lo = 0, hi = sizeof(kRanges) / sizeof(kRanges[0]);",
        "    while (lo < hi) {",
        "        size_t mid = (lo + hi) / 2;",
        "        if (kRanges[mid].last < cp) lo = mid + 1;",
        "        else if (kRanges[mid].first > cp) hi = mid;",
        "        else return kRanges[mid].bits;",
        "    }",
        "    return 0;",
        "}",
        "",
        "} // namespace unicode_class",
        "",
    ])


def nfc_tables(directory):
    """The combining-class runs, canonical decompositions, primary composites and quick-check runs NFC reads; Hangul syllables are algorithmic and left out."""
    ccc, decomposition = {}, {}
    for line in read_pinned(directory, "UnicodeData.txt").splitlines():
        fields = line.split(";")
        cp = int(fields[0], 16)
        if int(fields[3]):
            ccc[cp] = int(fields[3])
        if fields[5] and not fields[5].startswith("<"):
            decomposition[cp] = [int(x, 16) for x in fields[5].split()]
    excluded, quick = set(), set()
    for first, last, prop in entries(read_pinned(directory, "DerivedNormalizationProps.txt")):
        if prop == "Full_Composition_Exclusion":
            excluded.update(range(first, last + 1))
        elif prop == "NFC_QC":
            quick.update(range(first, last + 1))
    assert all(1 <= len(d) <= 2 for d in decomposition.values())
    compositions = sorted((d[0], d[1], cp) for cp, d in decomposition.items() if len(d) == 2 and cp not in excluded)
    return ranges(ccc), sorted(decomposition.items()), compositions, [r[:2] for r in ranges(dict.fromkeys(quick, 1))]


def rows(items, per_line):
    return ["    " + " ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]


def nfc_include(combining, decompositions, compositions, quick):
    return "\n".join([
        "// The Unicode %s tables NFC reads, included inside namespace unicode_nfc by core/unicode_nfc.hpp, which declares their types." % VERSION,
        "// Generated by tools/gen_unicode_table.py from UnicodeData.txt and DerivedNormalizationProps.txt; do not hand-edit.",
        "",
        "// Sorted runs of code points with the same nonzero canonical combining class.",
        "inline constexpr CombiningRun kCombining[] = {",
    ] + rows(["{0x%x, 0x%x, %d}," % tuple(r) for r in combining], 6) + [
        "};",
        "",
        "// Each canonical decomposition by code point, the second half 0 for a singleton.",
        "inline constexpr Decomposition kDecompositions[] = {",
    ] + rows(["{0x%x, 0x%x, 0x%x}," % (cp, d[0], d[1] if len(d) == 2 else 0) for cp, d in decompositions], 5) + [
        "};",
        "",
        "// Each primary composite by its two halves, sorted by first half then second.",
        "inline constexpr Composition kCompositions[] = {",
    ] + rows(["{0x%x, 0x%x, 0x%x}," % c for c in compositions], 5) + [
        "};",
        "",
        "// Sorted runs of code points whose NFC quick check is No or Maybe.",
        "inline constexpr Run kNotQuick[] = {",
    ] + rows(["{0x%x, 0x%x}," % tuple(r) for r in quick], 7) + [
        "};",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd", required=True, help="directory holding the four pinned files")
    args = parser.parse_args()
    runs = ranges(class_bits(args.ucd))
    with open(OUTPUT, "w", encoding="ascii", newline="\n") as f:
        f.write(header(runs))
    print("wrote %s (%d runs)" % (OUTPUT, len(runs)))
    tables = nfc_tables(args.ucd)
    with open(NFC_OUTPUT, "w", encoding="ascii", newline="\n") as f:
        f.write(nfc_include(*tables))
    print("wrote %s (%d combining runs, %d decompositions, %d compositions, %d quick-check runs)" % ((NFC_OUTPUT,) + tuple(len(t) for t in tables)))


if __name__ == "__main__":
    sys.exit(main())
